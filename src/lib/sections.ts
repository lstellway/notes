/**
 * The content sections: every folder under `src/content/docs/` that holds pages.
 *
 * This list is the single source of truth for the folder hierarchy. The sidebar in
 * `astro.config.ts` is built from it, and `sections.test.ts` fails if a folder with
 * pages is missing here, or if a section here has no folder.
 *
 * Rules (checked by `sections.test.ts`):
 * - A section with subsections has an overview page (`index.md` or `index.mdx`) and no
 *   other pages. Its other pages belong in a subsection.
 * - A section without subsections lists all of its pages in the sidebar, sorted by
 *   `sidebar.order` and then by title.
 * - Folder names are lowercase and hyphenated. `images` is reserved for images.
 *
 * To add a section, add an entry below and create its folder.
 */

export interface Section {
	/** Folder name inside the parent section (or inside `src/content/docs/` for a topic). */
	folder: string;
	/** Name shown in the sidebar. */
	label: string;
	/** Subsections, in sidebar order. */
	sections?: readonly Section[];
}

export const sections: readonly Section[] = [
	{
		folder: "finance",
		label: "Finance",
		sections: [
			{ folder: "mortgages", label: "Mortgages" },
			{ folder: "tools", label: "Tools" },
		],
	},
	{ folder: "contributing", label: "Contributing" },
];

/** A section with its position in the hierarchy worked out. */
export interface ResolvedSection {
	/** Path under `src/content/docs/`, e.g. "finance/mortgages". */
	path: string;
	/** Labels from the topic down to this section, e.g. ["Finance", "Mortgages"]. */
	labels: readonly string[];
	/** Whether the section has subsections. */
	hasSubsections: boolean;
	section: Section;
}

/** Every section in the tree, parents before their subsections, in sidebar order. */
export function flattenSections(
	list: readonly Section[] = sections,
	parent?: ResolvedSection,
): ResolvedSection[] {
	return list.flatMap((section) => {
		const resolved: ResolvedSection = {
			path: parent ? `${parent.path}/${section.folder}` : section.folder,
			labels: [...(parent?.labels ?? []), section.label],
			hasSubsections: (section.sections?.length ?? 0) > 0,
			section,
		};
		return [resolved, ...flattenSections(section.sections ?? [], resolved)];
	});
}

/** A Starlight sidebar group (the subset of Starlight's sidebar types used here). */
export interface SidebarGroup {
	label: string;
	items: (SidebarGroup | { slug: string } | { autogenerate: { directory: string } })[];
}

/**
 * Builds Starlight's `sidebar` option. A section with subsections shows its overview
 * page, then one group per subsection. A section without subsections lists its pages.
 *
 * Autogenerated groups aren't used for parents because Starlight would label each
 * subfolder with its raw folder name (e.g. "mortgages").
 */
export function buildSidebar(
	list: readonly Section[] = sections,
	parentPath?: string,
): SidebarGroup[] {
	return list.map((section) => {
		const path = parentPath ? `${parentPath}/${section.folder}` : section.folder;
		const subsections = section.sections ?? [];
		if (subsections.length === 0) {
			return { label: section.label, items: [{ autogenerate: { directory: path } }] };
		}
		return { label: section.label, items: [{ slug: path }, ...buildSidebar(subsections, path)] };
	});
}
